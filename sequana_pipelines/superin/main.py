import os

import rich_click as click
import click_completion

click_completion.init()


from sequana_pipetools.options import *
from sequana_pipetools import SequanaManager


NAME = "superin"

help = init_click(NAME, groups={
    "Pipeline Specific": [
        "--method", "--skip-multiqc"],
        }
)



@click.command(context_settings=help)
@include_options_from(ClickSnakemakeOptions, working_directory=NAME)
@include_options_from(ClickSlurmOptions)
@include_options_from(ClickInputOptions,
    input_directory="data/fastq",
    add_input_readtag=False)
@include_options_from(ClickGeneralOptions)
@click.option(
    "--input-bam-pattern",
    default="data/bam",
    help="""pattern to find BAM files generated by sequana_nanocap (or any mapper tool)""",
)
@click.option(
    "--samplesheet",
    required=True,
    help="""a 3-column CSV file with column 'sample', 'plasmid', 'reference'. sample is suppose to match your input BAM files (named as SAMPLE.sorted.bam). The plasmid should match the reference. reference should contain the SI + plasmid in fasta format. If no plasmids were used, let the plasmid column empty.  """)


@click.option(
    "--plasmids-directory",
    required=True,
    help="""directory where to find the plasmid references. samplesheet will give filename (without directory)""")

@click.option(
    "--SI-reference-file",
    "SI_reference_file",
    required=True,
    help="""directory where to find the plasmid references. samplesheet will give filename (without directory)""")

def main(**options):


    # the real stuff is here
    manager = SequanaManager(options, NAME)
    options = manager.options

    # creates the working directory
    manager.setup()

    # Fill the config file with data and specific options
    cfg = manager.config.config
    cfg.input_pattern = options.input_pattern
    cfg.input_directory = os.path.abspath(options.input_directory)

    cfg.input_bam_pattern = os.path.abspath(options.input_bam_pattern)
    manager.exists(cfg.input_directory)
    
    cfg.SI_reference_file = os.path.abspath(options.SI_reference_file)
    cfg.plasmids_directory = os.path.abspath(options.plasmids_directory)

    # no need for abspath. we will copy it
    cfg.samplesheet = options.samplesheet

    # finalise the command and save it; copy the snakemake. update the config
    # file and save it.
    manager.teardown()

    import shutil
    shutil.copy(options.samplesheet, manager.workdir)


if __name__ == "__main__":
    main()
